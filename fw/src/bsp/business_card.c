////////////////////////////////////////////////////////////////////////////////////////////////////
// Include(s)
////////////////////////////////////////////////////////////////////////////////////////////////////
#include "business_card.h"

#include <xc.h>

////////////////////////////////////////////////////////////////////////////////////////////////////
// Definition(s)
////////////////////////////////////////////////////////////////////////////////////////////////////
#define SEL_PIN 1U << 7U

////////////////////////////////////////////////////////////////////////////////////////////////////
// Global(s)
////////////////////////////////////////////////////////////////////////////////////////////////////
extern volatile bool g_mode;

////////////////////////////////////////////////////////////////////////////////////////////////////
void config(void)
{
   // MCU Config:
   config_gpio();
   config_i2c();

   // HW Config:
   config_sseg_display();

   return;
}

////////////////////////////////////////////////////////////////////////////////////////////////////
void __interrupt() ISR(void) 
{
   if (IOCCF & SEL_PIN) // SELECT Pin Interrupt
   {
      // Deglitch:
      __delay_ms(10);

      g_mode = !g_mode;
      set_display_indicator_mode(g_mode);

      // Clear interrupt:
      IOCCF &= ~SEL_PIN;
   }

   return;
}
