#ifndef HW_DRIVERS_SSEG_DISPLAY_H
#define HW_DRIVERS_SSEG_DISPLAY_H

////////////////////////////////////////////////////////////////////////////////////////////////////
// Include(s)
////////////////////////////////////////////////////////////////////////////////////////////////////
#include <stdint.h>

////////////////////////////////////////////////////////////////////////////////////////////////////
/// @brief Configures the initial state of the 7-seg displays.
////////////////////////////////////////////////////////////////////////////////////////////////////
void config_sseg_display(void);

////////////////////////////////////////////////////////////////////////////////////////////////////
/// @brief Sets a digit.
///
/// @param[in] dig The digit to set.
/// @param[in] val The value to set the digit to.
////////////////////////////////////////////////////////////////////////////////////////////////////
void set_sseg_digit(uint8_t dig, uint8_t val);

////////////////////////////////////////////////////////////////////////////////////////////////////
/// @brief Encodes a digit input.
///
/// @param[in] val_dec Decimal value to write to 7-seg display.
///
/// @return Hex value to write to 7-seg display.
////////////////////////////////////////////////////////////////////////////////////////////////////
uint8_t _encode_dec(uint8_t val_dec);

#endif // HW_DRIVERS_SSEG_DISPLAY_H
