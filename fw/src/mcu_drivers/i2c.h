#ifndef MCU_DRIVERS_I2C_H
#define MCU_DRIVERS_I2C_H

////////////////////////////////////////////////////////////////////////////////////////////////////
// Include(s)
////////////////////////////////////////////////////////////////////////////////////////////////////
#include <stdint.h>

////////////////////////////////////////////////////////////////////////////////////////////////////
/// @brief Configures the I2C peripheral.
////////////////////////////////////////////////////////////////////////////////////////////////////
void config_i2c(void);

////////////////////////////////////////////////////////////////////////////////////////////////////
/// @brief Send a package across the I2C bus.
///
/// @param[in] addr Slave I2C address.
/// @param[in] reg  Slave register to write to.
/// @param[in] data Data to write to slave.
////////////////////////////////////////////////////////////////////////////////////////////////////
void i2c_transmit_data(uint8_t addr, uint8_t reg, uint8_t data);

////////////////////////////////////////////////////////////////////////////////////////////////////
/// @brief Receives data from devices on the I2C bus.
///
/// @param[in] addr Slave I2C address.
/// @param[in] reg Slave register to read from.
////////////////////////////////////////////////////////////////////////////////////////////////////
uint8_t i2c_receive_data(uint8_t addr, uint8_t reg);

////////////////////////////////////////////////////////////////////////////////////////////////////
/// @brief Starts an I2C transaction.
////////////////////////////////////////////////////////////////////////////////////////////////////
void _i2c_start(void);

////////////////////////////////////////////////////////////////////////////////////////////////////
/// @brief Stops an I2C transaction.
////////////////////////////////////////////////////////////////////////////////////////////////////
void _i2c_stop(void);

////////////////////////////////////////////////////////////////////////////////////////////////////
/// @brief Writes a byte to the I2C bus.
///
/// @param[in] data Byte to write.
////////////////////////////////////////////////////////////////////////////////////////////////////
void _i2c_write_byte(uint8_t data);

////////////////////////////////////////////////////////////////////////////////////////////////////
/// @brief Reads a byte from the I2C bus.
////////////////////////////////////////////////////////////////////////////////////////////////////
uint8_t _i2c_read_byte(void);

#endif // MCU_DRIVERS_I2C_H
