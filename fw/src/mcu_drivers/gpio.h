#ifndef MCU_DRIVERS_GPIO_H
#define MCU_DRIVERS_GPIO_H

////////////////////////////////////////////////////////////////////////////////////////////////////
// Include(s)
////////////////////////////////////////////////////////////////////////////////////////////////////
#include <stdint.h>

////////////////////////////////////////////////////////////////////////////////////////////////////
/// @brief Sets a GPIO pin.
///
/// @param[in] bank The bank to set.
/// @param[in] pin  The pin to set.
////////////////////////////////////////////////////////////////////////////////////////////////////
void set_pin(char bank, uint8_t pin);

////////////////////////////////////////////////////////////////////////////////////////////////////
/// @brief Clears a GPIO pin.
///
/// @param[in] bank The bank to clear.
/// @param[in] pin  The pin to clear.
////////////////////////////////////////////////////////////////////////////////////////////////////
void clear_pin(char bank, uint8_t pin);

#endif // MCU_DRIVERS_GPIO_H
