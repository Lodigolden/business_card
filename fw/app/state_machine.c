////////////////////////////////////////////////////////////////////////////////////////////////////
// Include(s)
////////////////////////////////////////////////////////////////////////////////////////////////////
#include "state_machine.h"

#include <xc.h>

////////////////////////////////////////////////////////////////////////////////////////////////////
// Definition(s)
////////////////////////////////////////////////////////////////////////////////////////////////////
#define TICK_RATE 100

////////////////////////////////////////////////////////////////////////////////////////////////////
// Global(s)
////////////////////////////////////////////////////////////////////////////////////////////////////
volatile bool g_mode = CLOCK;

////////////////////////////////////////////////////////////////////////////////////////////////////
void system_state_machine(void)
{
   // State Variables
   uint8_t count = 0U;

   while(1)
   {
      if (!g_mode)
      {
         set_sseg_digit(0U, count);
         count = (count == 9U) ? 0U : count + 1U;
      }

      __delay_ms(1000);
   }

   return;
}
