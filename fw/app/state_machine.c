#include "state_machine.h"

#include <xc.h>

////////////////////////////////////////////////////////////////////////////////////////////////////
// Definition(s)
////////////////////////////////////////////////////////////////////////////////////////////////////
#define TICK_RATE 100

////////////////////////////////////////////////////////////////////////////////////////////////////
// Global(s)
////////////////////////////////////////////////////////////////////////////////////////////////////
volatile bool g_mode = CLOCK;

////////////////////////////////////////////////////////////////////////////////////////////////////
void system_state_machine(void)
{
   // State Variables
   uint8_t count = 0U;

   while(1)
   {
      if (!g_mode)
      {
         for (uint8_t idx = 0U; idx < 3U; idx++)
         {
            set_sseg_digit(idx, count);
         }
         count = (count == 15U) ? 0U : count + 1U;
      }

      __delay_ms(1000);
   }

   return;
}
