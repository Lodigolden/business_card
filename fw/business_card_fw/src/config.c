#include "config.h"

////////////////////////////////////////////////////////////////////////////////////////////////////
void config(void)
{
   // Initial reset:
   PORTC = 0x00;
   LATC = 0x00;
   ANSELC = 0x00;
   TRISC = 0xFF;

   // Config MODE Led:
   TRISC &= ~(1U << 3U);
}
